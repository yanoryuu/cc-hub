// 会話履歴とフォルダ選択の純粋ロジックのテスト(タイトル抽出 / 絞り込み / フォルダ名の除外)。
// 実行: npm run test -w @cc-hub/daemon
import assert from 'node:assert/strict';
import type { HistoryEntry } from '@cc-hub/shared';
import { combineChunks, extractMessages, filterHistory, isTestCwd, parseChunk, underPath, userPromptText } from '../src/history';
import { filterDirNames, isSkippedDirName } from '../src/fsdirs';

let passed = 0;
function test(name: string, fn: () => void): void {
  try {
    fn();
    passed++;
    console.log(`ok   ${name}`);
  } catch (e) {
    console.log(`FAIL ${name}\n     ${(e as Error).message}`);
    process.exitCode = 1;
  }
}

const CWD = 'D:\\Unity\\TomsLands';
let n = 0;
function ts(): string {
  return new Date(Date.UTC(2026, 9, 1, 0, 0, n++)).toISOString();
}
function user(content: unknown, extra: Record<string, unknown> = {}): string {
  return JSON.stringify({ type: 'user', isSidechain: false, cwd: CWD, gitBranch: 'main', timestamp: ts(), message: { role: 'user', content }, ...extra });
}
function assistant(blocks: unknown[], extra: Record<string, unknown> = {}): string {
  return JSON.stringify({ type: 'assistant', isSidechain: false, cwd: CWD, timestamp: ts(), message: { role: 'assistant', content: blocks }, ...extra });
}
const CAVEAT = user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>');
const CAVEAT_OLD = user('Caveat: The messages below were generated by the user while running local commands.');
const CLEAR = user('<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>');
const STDOUT = user('<local-command-stdout></local-command-stdout>');
const TOOL_RESULT = user([{ type: 'tool_result', tool_use_id: 'x', content: 'ファイルの中身' }]);
const SLASH = user('<command-message>hub-commander</command-message>\n<command-name>/hub-commander</command-name>\n<command-args>README を 1 行で要約して</command-args>');
const SKILL_BODY = user([{ type: 'text', text: 'Base directory for this skill: ...' }], { isMeta: true });

// ---------------------------------------------------------------- タイトル抽出
test('最初の発言がタイトル(ツール結果・Caveat・組み込みコマンドは飛ばす)', () => {
  const text = [
    JSON.stringify({ type: 'permission-mode', permissionMode: 'auto' }),
    CAVEAT,
    CAVEAT_OLD,
    CLEAR,
    STDOUT,
    TOOL_RESULT,
    user([{ type: 'text', text: '  勇者のステータスが出ない原因を調べて  ' }]),
    assistant([{ type: 'text', text: '調べます' }, { type: 'tool_use', name: 'Grep', input: { pattern: 'Status' } }]),
    TOOL_RESULT,
    assistant([{ type: 'text', text: '原因は\nHUD の初期化順です' }]),
    user('ありがとう'),
  ].join('\n');
  const info = combineChunks(parseChunk(text), null)!;
  assert.equal(info.title, '勇者のステータスが出ない原因を調べて');
  assert.equal(info.cwd, CWD);
  assert.equal(info.messageCount, 2);
  assert.equal(info.lastMessage, '原因は HUD の初期化順です');
  assert.equal(info.gitBranch, 'main');
  assert.ok(info.createdAt && info.createdAt > 0);
});

test('スラッシュコマンドは "/名前 引数" で表示(スキル展開の isMeta 行は数えない)', () => {
  const info = combineChunks(parseChunk([CAVEAT, SLASH, SKILL_BODY, assistant([{ type: 'text', text: 'OK' }])].join('\n')), null)!;
  assert.equal(info.title, '/hub-commander README を 1 行で要約して');
  assert.equal(info.messageCount, 1);
});

test('引数なしのカスタムコマンドは発言、組み込みコマンドは発言にしない', () => {
  assert.equal(userPromptText(JSON.parse(user('<command-message>cchub-spike</command-message>\n<command-name>/cchub-spike</command-name>'))), '/cchub-spike');
  assert.equal(userPromptText(JSON.parse(CLEAR)), null);
  assert.equal(userPromptText(JSON.parse(user('<command-name>/model</command-name><command-args>haiku</command-args>'))), '/model haiku');
});

test('ツール結果だけ・Caveat だけの transcript は一覧に出さない(null)', () => {
  assert.equal(combineChunks(parseChunk([CAVEAT, CLEAR, STDOUT, TOOL_RESULT].join('\n')), null), null);
});

test('サイドチェーン(サブエージェント)の発言は使わない', () => {
  const side = user('サブエージェントへの指示', { isSidechain: true });
  const info = combineChunks(parseChunk([side, user('本当の指示')].join('\n')), null)!;
  assert.equal(info.title, '本当の指示');
});

test('タイトルの優先順位: custom-title > summary > 最初の発言 > ai-title', () => {
  const base = [user('最初の発言')];
  const ai = JSON.stringify({ type: 'ai-title', aiTitle: 'AI のタイトル' });
  const sum = JSON.stringify({ type: 'summary', summary: '要約' });
  const custom = JSON.stringify({ type: 'custom-title', customTitle: '名前を付けた' });
  assert.equal(combineChunks(parseChunk([...base, ai].join('\n')), null)!.title, '最初の発言');
  assert.equal(combineChunks(parseChunk([sum, ...base, ai].join('\n')), null)!.title, '要約');
  assert.equal(combineChunks(parseChunk(base.join('\n')), parseChunk(custom))!.title, '名前を付けた');
});

test('壊れた行・途中で切れた行は飛ばす / 先頭 + 末尾の発言数は通し番号で補う', () => {
  const head = parseChunk([user('はじめ', { turnPosition: { promptIndex: 1 } }), '{"type":"user","mess'].join('\n'));
  const tail = parseChunk(['ge":"x"}', user('おわり', { turnPosition: { promptIndex: 37 } }), assistant([{ type: 'text', text: '完了' }]), ''].join('\n'));
  const info = combineChunks(head, tail)!;
  assert.equal(info.title, 'はじめ');
  assert.equal(info.messageCount, 37);
  assert.equal(info.lastMessage, '完了');
});

test('extractMessages: user / assistant / tool の行', () => {
  const items = extractMessages(
    [CAVEAT, SLASH, TOOL_RESULT, assistant([{ type: 'text', text: '了解' }, { type: 'tool_use', name: 'Read', input: { file_path: 'D:\\a.ts' } }])].join('\n'),
  );
  assert.deepEqual(
    items.map((i) => [i.role, i.text]),
    [
      ['user', '/hub-commander README を 1 行で要約して'],
      ['assistant', '了解'],
      ['tool', 'Read: D:\\a.ts'],
    ],
  );
  assert.ok(items.every((i) => i.ts > 0));
});

// ---------------------------------------------------------------- 絞り込み
function entry(id: string, cwd: string, title: string, mtime: number, lastMessage: string | null = null): HistoryEntry {
  return { id, cwd, title, mtime, lastMessage };
}
const ENTRIES: HistoryEntry[] = [
  entry('a', 'D:\\Unity\\TomsLands', 'HUD の修正', 3),
  entry('b', 'C:\\Users\\yanor\\cc-hub', 'CC Hub の履歴画面', 5, 'done'),
  entry('c', 'D:\\Unity\\TomsLandsOld', '古い方', 4),
  entry('d', 'D:\\AITEST\\p6', '検証', 9),
  entry('e', 'D:\\WorkTree\\_test-x\\wt-01', '検証 2', 8),
  entry('f', 'C:\\Users\\yanor\\AppData\\Local\\Temp\\claude\\C--Users-yanor\\abc\\scratchpad\\p2', '検証 3', 7),
  entry('g', 'D:\\Unity\\TomsLands\\Assets', '配下', 2, 'ステータス表示を直しました'),
];

test('既定では検証フォルダを除き、新しい順', () => {
  assert.deepEqual(filterHistory(ENTRIES, {}).map((e) => e.id), ['b', 'c', 'a', 'g']);
  assert.deepEqual(filterHistory(ENTRIES, { includeTests: true }).map((e) => e.id), ['d', 'e', 'f', 'b', 'c', 'a', 'g']);
  assert.ok(isTestCwd('d:/aitest/p6'));
  assert.ok(!isTestCwd('D:\\AITESTING'));
});

test('q: タイトル / cwd / 最後の発言の部分一致(大文字小文字無視)', () => {
  assert.deepEqual(filterHistory(ENTRIES, { q: 'tomslands' }).map((e) => e.id), ['c', 'a', 'g']);
  assert.deepEqual(filterHistory(ENTRIES, { q: 'cc hub' }).map((e) => e.id), ['b']);
  assert.deepEqual(filterHistory(ENTRIES, { q: 'ステータス' }).map((e) => e.id), ['g']);
  assert.deepEqual(filterHistory(ENTRIES, { q: '存在しない' }), []);
});

test('cwd: フォルダ自身と配下だけ(前方一致の別フォルダは含まない)', () => {
  assert.deepEqual(filterHistory(ENTRIES, { cwd: 'd:\\unity\\tomslands\\' }).map((e) => e.id), ['a', 'g']);
  assert.deepEqual(filterHistory(ENTRIES, { cwd: 'D:/Unity/TomsLands', q: '配下' }).map((e) => e.id), ['g']);
  assert.ok(underPath('D:\\Unity', 'D:\\'));
  assert.ok(!underPath('D:\\UnityX', 'D:\\Unity'));
});

// ---------------------------------------------------------------- フォルダ選択
test('隠し・システム・依存物のフォルダは除く', () => {
  for (const n of ['.git', '.vscode', 'node_modules', '$RECYCLE.BIN', 'System Volume Information', 'AppData', 'My Documents', '$WinREAgent']) {
    assert.ok(isSkippedDirName(n), n);
  }
  for (const n of ['Unity', 'cc-hub', 'Program Files', 'src']) assert.ok(!isSkippedDirName(n), n);
});

test('並び順(大文字小文字を区別しない・数字は自然順)と上限', () => {
  assert.deepEqual(filterDirNames(['b', 'node_modules', 'A', 'wt-10', 'wt-2', '.claude', 'c']), ['A', 'b', 'c', 'wt-2', 'wt-10']);
  assert.equal(filterDirNames(Array.from({ length: 600 }, (_, i) => `d${i}`)).length, 500);
});

console.log(`\n${passed} passed${process.exitCode ? ' (FAILURES)' : ''}`);
